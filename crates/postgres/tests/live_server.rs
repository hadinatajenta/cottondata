use cottondata_core::{ConnectionEndpoint, DatabaseEngine, ServerProfile, SqlDialect, TlsMode};
use cottondata_driver::{DatabaseSession, QueryOutcome};
use cottondata_grid::ColumnarPage;
use cottondata_postgres::PostgresSession;
use std::time::{Duration, Instant};

struct LiveTarget {
    profile: ServerProfile,
    password: Option<String>,
}

fn live_target() -> Option<LiveTarget> {
    let host = std::env::var("COTTONDATA_PG_HOST").ok()?;
    let port = std::env::var("COTTONDATA_PG_PORT")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(5432);
    let user = std::env::var("COTTONDATA_PG_USER").unwrap_or_else(|_| "postgres".into());
    let is_cockroach = std::env::var("COTTONDATA_PG_ENGINE").is_ok_and(|engine| engine.eq_ignore_ascii_case("cockroach"));
    let mut profile = ServerProfile::new_local("live-postgres", host.clone(), port, user);
    profile.engine = if is_cockroach {
        DatabaseEngine::CockroachDb
    } else {
        DatabaseEngine::PostgreSql
    };
    profile.endpoint = ConnectionEndpoint::Tcp { host, port };
    profile.ssh.enabled = false;
    profile.tls = TlsMode::Preferred;
    profile.default_schema = std::env::var("COTTONDATA_PG_DATABASE").ok();
    Some(LiveTarget {
        profile,
        password: std::env::var("COTTONDATA_PG_PASSWORD").ok(),
    })
}

fn rows(session: &mut PostgresSession, sql: &str, max_rows: u32) -> ColumnarPage {
    match session.execute_sql(sql, max_rows).unwrap_or_else(|error| panic!("{sql}: {error}")) {
        QueryOutcome::Rows(page) => page,
        QueryOutcome::Affected { .. } => panic!("expected rows from {sql}"),
    }
}

fn affected(session: &mut PostgresSession, sql: &str) -> u64 {
    match session.execute_sql(sql, 10).unwrap_or_else(|error| panic!("{sql}: {error}")) {
        QueryOutcome::Affected { affected_rows, .. } => affected_rows,
        QueryOutcome::Rows(_) => panic!("expected affected rows from {sql}"),
    }
}

fn count(session: &mut PostgresSession, table: &str) -> String {
    rows(session, &format!("SELECT count(*) FROM {table}"), 1)
        .cell_str(0, 0)
        .unwrap_or_default()
        .to_string()
}

#[test]
fn full_round_trip_against_live_postgres_family_server() {
    let Some(target) = live_target() else {
        eprintln!("skipped: set COTTONDATA_PG_HOST (and optionally _PORT, _USER, _PASSWORD, _DATABASE, _ENGINE=cockroach)");
        return;
    };
    let password = target.password.as_deref();
    let mut session = PostgresSession::connect(&target.profile, password).expect("connect");
    let is_cockroach = session.dialect() == SqlDialect::CockroachDb;
    assert!(!session.runtime().version.is_empty());
    let schema = format!("cottondata_live_{}", std::process::id());
    let _ = session.execute_sql(&format!("DROP SCHEMA IF EXISTS {schema} CASCADE"), 1);
    affected(&mut session, &format!("CREATE SCHEMA {schema}"));
    session.set_schema(&schema).expect("set schema");
    assert_eq!(session.runtime().current_schema.as_deref(), Some(schema.as_str()));

    affected(
        &mut session,
        "CREATE TABLE customers (id INT8 PRIMARY KEY, name TEXT NOT NULL UNIQUE)",
    );
    affected(
        &mut session,
        "CREATE TABLE orders (\
            id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
            customer_id INT8 REFERENCES customers (id) ON DELETE CASCADE, \
            note TEXT, total NUMERIC(12,2) NOT NULL DEFAULT 0, paid BOOL NOT NULL DEFAULT false, \
            placed_at TIMESTAMPTZ NOT NULL DEFAULT now(), payload JSONB, raw BYTEA, tags INT8[])",
    );
    affected(&mut session, "CREATE INDEX ix_orders_note ON orders (note)");
    assert_eq!(affected(&mut session, "INSERT INTO customers VALUES (1, 'Ana'), (2, 'Budi')"), 2);
    assert_eq!(
        affected(
            &mut session,
            "INSERT INTO orders (customer_id, note, total, paid, payload, raw, tags) VALUES \
             (1, 'first', 12.50, true, '{\"a\": 1}', '\\x0aff', ARRAY[1,2]), \
             (2, 'second; with semicolon', 3, false, NULL, NULL, NULL)"
        ),
        2
    );

    let returned = rows(&mut session, "INSERT INTO orders (customer_id, note) VALUES (1, 'third') RETURNING id, note", 10);
    assert_eq!(returned.row_count, 1);
    assert_eq!(returned.cell_str(0, 1), Some("third"));

    let page = rows(
        &mut session,
        "SELECT id, note, total, paid, payload, raw, tags, placed_at FROM orders ORDER BY id",
        100,
    );
    assert_eq!(page.row_count, 3);
    assert_eq!(page.cell_str(0, 2), Some("12.50"));
    assert_eq!(page.cell_str(0, 3), Some("true"));
    assert_eq!(page.cell_str(1, 3), Some("false"));
    assert_eq!(page.cell_str(0, 5), Some("\\x0aff"));
    assert_eq!(page.cell_str(0, 6), Some("{1,2}"));
    assert!(page.cell_str(1, 4).is_none(), "NULL jsonb stays NULL");
    let id_column = &page.columns[0];
    assert!(id_column.is_numeric && id_column.is_primary_key, "{id_column:?}");
    assert_eq!(id_column.table.as_deref(), Some("orders"));
    assert_eq!(id_column.schema.as_deref(), Some(schema.as_str()));
    assert_eq!(page.columns[1].org_name.as_deref(), Some("note"));
    assert!(page.columns[5].is_binary);
    assert!(!page.columns[2].is_nullable);

    affected(
        &mut session,
        "INSERT INTO orders (customer_id, note) SELECT 2, 'bulk ' || g::text FROM generate_series(1, 50) AS g",
    );
    let limited = rows(&mut session, "SELECT * FROM orders ORDER BY id", 10);
    assert_eq!(limited.row_count, 10);
    assert!(limited.has_more_rows);
    assert!(!session.runtime().in_transaction, "cursor read must not leave a transaction open");

    let huge_started = Instant::now();
    let huge = rows(&mut session, "SELECT g, md5(g::text) FROM generate_series(1, 50000000) AS g", 10);
    assert_eq!(huge.row_count, 10);
    assert!(huge.has_more_rows);
    assert!(huge_started.elapsed() < Duration::from_secs(8), "huge read took {:?}", huge_started.elapsed());
    assert_eq!(rows(&mut session, "SELECT 7", 1).cell_str(0, 0), Some("7"), "session stays usable after the capped read");

    let first_of_script = rows(&mut session, "SELECT 1 AS a; SELECT 2 AS b", 10);
    assert_eq!(first_of_script.cell_str(0, 0), Some("1"));

    if !is_cockroach {
        affected(
            &mut session,
            "CREATE FUNCTION add_one(value int) RETURNS int AS $$\nBEGIN\n  RETURN value + 1;\nEND;\n$$ LANGUAGE plpgsql",
        );
        assert_eq!(rows(&mut session, "SELECT add_one(41)", 1).cell_str(0, 0), Some("42"));
    }

    let syntax_error = session
        .execute_sql("SELECT *\nFROM orders\nWHERE nope = 1", 1)
        .expect_err("unknown column");
    assert!(syntax_error.to_string().contains("nope"), "{syntax_error}");
    assert!(!session.runtime().in_transaction);

    let before = count(&mut session, "orders");
    session.begin_transaction().expect("begin");
    affected(&mut session, "DELETE FROM orders WHERE note = 'first'");
    let inside = rows(&mut session, "SELECT note FROM orders ORDER BY id", 100);
    assert!(inside.row_count > 0, "cursor read works inside an open transaction");
    session.rollback().expect("rollback");
    assert_eq!(count(&mut session, "orders"), before);

    session.set_autocommit(false).expect("manual commit");
    affected(&mut session, "DELETE FROM orders WHERE note = 'second; with semicolon'");
    assert!(session.runtime().in_transaction, "manual commit opens a transaction implicitly");
    session.rollback().expect("rollback manual");
    session.set_autocommit(true).expect("auto commit");
    assert_eq!(count(&mut session, "orders"), before);

    let batch_error = session.execute_atomic_batch(&[
        "UPDATE orders SET note = 'changed' WHERE note = 'first'".to_string(),
        "UPDATE orders SET missing_column = 1".to_string(),
    ]);
    assert!(batch_error.is_err());
    assert_eq!(rows(&mut session, "SELECT count(*) FROM orders WHERE note = 'changed'", 1).cell_str(0, 0), Some("0"));
    session
        .execute_atomic_batch(&["UPDATE orders SET note = 'changed' WHERE note = 'first'".to_string()])
        .expect("batch commit");
    assert_eq!(rows(&mut session, "SELECT count(*) FROM orders WHERE note = 'changed'", 1).cell_str(0, 0), Some("1"));

    let mut streamed = 0u64;
    let mut column_count = 0usize;
    let total = session
        .stream_query(
            "SELECT id, note FROM orders",
            &mut |columns| {
                column_count = columns.len();
                Ok(())
            },
            &mut |_| {
                streamed += 1;
                Ok(true)
            },
        )
        .expect("stream");
    assert_eq!((total, streamed, column_count), (53, 53, 2));

    let plan = session.explain("SELECT * FROM orders WHERE id = 1", false).expect("explain");
    assert!(!plan.raw_output.is_empty());
    let analyzed = session.explain("DELETE FROM orders", true).expect("explain analyze");
    assert!(!analyzed.raw_output.is_empty());
    assert_eq!(count(&mut session, "orders"), before, "EXPLAIN ANALYZE must roll back");

    let schemas = session.list_schemas().expect("schemas");
    assert!(schemas.iter().any(|summary| summary.name == schema && !summary.is_system));
    let objects = session.load_schema_objects(&schema).expect("objects");
    let orders = objects.tables.iter().find(|table| table.name == "orders").expect("orders listed");
    assert!(orders.columns.iter().any(|column| column.name == "id" && column.is_primary_key && column.is_auto_increment));
    assert!(orders.columns.iter().any(|column| column.name == "total"
        && (column.column_type.contains("numeric") || column.column_type.contains("decimal"))));
    let detail = session.load_table_detail(&schema, "orders").expect("detail");
    assert!(detail.ddl.contains("CREATE TABLE"), "{}", detail.ddl);
    assert!(detail.indexes.iter().any(|index| index.columns.contains(&"note".to_string())));
    assert!(detail
        .foreign_keys
        .iter()
        .any(|foreign_key| foreign_key.column_name == "customer_id" && foreign_key.ref_table == "customers"));
    let customers = session.load_table_detail(&schema, "customers").expect("customers detail");
    assert!(customers
        .inbound_foreign_keys
        .iter()
        .any(|inbound| inbound.source_table == "orders" && inbound.source_column == "customer_id"));

    assert!(!session.fetch_processlist().expect("processlist").is_empty());
    assert!(!session.fetch_health_metrics().expect("health").metrics.is_empty());

    let profile = target.profile.clone();
    let cancel_password = target.password.clone();
    let connection_id = session.runtime().connection_id;
    let canceller = std::thread::spawn(move || {
        std::thread::sleep(Duration::from_millis(700));
        PostgresSession::kill_query_via_aux(&profile, cancel_password.as_deref(), connection_id)
    });
    let started = Instant::now();
    let cancelled = session.execute_sql("SELECT pg_sleep(20)", 1);
    canceller.join().expect("cancel thread").expect("cancel request");
    assert!(cancelled.is_err(), "sleep should be cancelled");
    assert!(started.elapsed() < Duration::from_secs(10), "cancel took {:?}", started.elapsed());
    rows(&mut session, "SELECT 1", 1);

    let mut read_only_profile = target.profile.clone();
    read_only_profile.read_only = true;
    let mut read_only = PostgresSession::connect(&read_only_profile, password).expect("read-only connect");
    read_only.set_schema(&schema).expect("read-only schema");
    assert!(read_only.execute_sql("DELETE FROM orders", 1).is_err());
    assert!(read_only.execute_sql("SELECT * FROM orders", 5).is_ok());
    drop(read_only);

    affected(&mut session, &format!("DROP SCHEMA {schema} CASCADE"));
}
